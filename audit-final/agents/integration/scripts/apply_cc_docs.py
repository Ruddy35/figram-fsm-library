import os, sys

W = sys.argv[1]


def edit(path, pairs):
    p = os.path.join(W, path)
    s = open(p, encoding="utf-8").read()
    for old, new in pairs:
        assert s.count(old) == 1, (path, old[:60])
        s = s.replace(old, new)
    open(p, "w", encoding="utf-8").write(s)


